export function normalizeLanguageName(value?: string): string | undefined {
  const normalized = value?.trim().toLowerCase().replace(/[\s-]+/g, " ");
  if (!normalized) return undefined;
  const aliased = LANGUAGE_ALIASES[normalized];
  if (aliased) return aliased;
  const key = normalized.replace(/\s+/g, "_");
  if (LANGUAGE_LABELS[key]) return key;
  if (!/^[a-z][a-z _]{1,39}$/.test(normalized)) return undefined;
  return key;
}

export function languageLabel(language: string): string {
  const key = normalizeLanguageName(language) ?? language;
  return LANGUAGE_LABELS[key] ?? key.replace(/_/g, " ").replace(/\b\w/g, (character) => character.toUpperCase());
}
